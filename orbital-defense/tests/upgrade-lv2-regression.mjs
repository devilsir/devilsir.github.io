import fs from "node:fs";
const src=fs.readFileSync(new URL("../game.js",import.meta.url),"utf8");
const fail=(m)=>{console.error("FAIL:",m);process.exitCode=1};
const section=(name,next)=>{const a=src.indexOf(`function ${name}`);const b=next?src.indexOf(`function ${next}`,a+1):src.length;return src.slice(a,b<0?src.length:b)};
const upgrade=section("upgradeSelectedTower","sellSelectedTower");
const moon=section("upgradeMoon","hideTowerPanel");
if(/\bpaused\b/.test(upgrade.split("\n")[1]||""))fail("upgradeSelectedTower ainda bloqueia pausa");
if(/\bpaused\b/.test(moon.split("\n")[1]||""))fail("upgradeMoon ainda bloqueia pausa");
if(!src.includes("level<4"))fail("linha principal não chega ao nível 4");
if(!src.includes("branchLevel>=2"))fail("especializações não chegam ao nível 2");
if(!src.includes("Nível 4 completo · escolha uma especialização"))fail("escolha de especialização não ocorre após o nível 4");
if(!src.includes("branchPanel.dataset.renderKey!==branchKey"))fail("especializações ainda são recriadas a cada refresh");
if(!process.exitCode)console.log("PASS: linha principal Lv1–4 + especialização Nv1–2 estável, inclusive durante pausa");
