import fs from 'node:fs';
const game=fs.readFileSync(new URL('../game.js',import.meta.url),'utf8');
const content=fs.readFileSync(new URL('../js/content.js',import.meta.url),'utf8');
const progress=fs.readFileSync(new URL('../js/progress.js',import.meta.url),'utf8');
const css=fs.readFileSync(new URL('../style.css',import.meta.url),'utf8');
const fail=m=>{console.error('FAIL:',m);process.exitCode=1};
if(!content.includes("collector:{name:'Singularidade Coletora'"))fail('Singularidade Coletora ausente');
if(!content.includes("['pulsar','collector']"))fail('coletor não está na progressão gradual da fase 7');
if(!progress.includes('collector:6'))fail('coletor não está na migração de progresso');
if(!game.includes("u.kind==='collector'"))fail('lógica de coleta automática ausente');
if(!game.includes('setupCollectorTraining'))fail('situação específica de treino do coletor ausente');
if(!game.includes('const thresholds=[.20,.52,.84]'))fail('checkpoints não foram mais espaçados');
if(!css.includes('left:20%')||!css.includes('left:52%')||!css.includes('left:84%'))fail('marcadores visuais dos checkpoints desalinhados');
if(!fs.existsSync(new URL('../assets/defender_collector.png',import.meta.url)))fail('asset do coletor ausente');
if(!process.exitCode)console.log('PASS: coletor automático, fase 7, treino, checkpoints e layout de progressão presentes');
