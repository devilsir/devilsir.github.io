const COLOR_WORDS = {
  sun: 'solar',
  mint: 'menta',
  rose: 'rosa',
  violet: 'violeta'
};

let currentLanguage = 'pt-BR';
let observer = null;
let onLanguageChange = null;
const textSources = new WeakMap();
const attributeSources = new WeakMap();
const TRANSLATABLE_ATTRIBUTES = ['aria-label', 'title', 'placeholder', 'content'];

function translateStatePhrase(source) {
  const states = {
    'low health': 'com a saúde baixa',
    hungry: 'com fome',
    tired: 'cansado',
    dirty: 'sujo',
    'sad or unmotivated': 'triste ou desanimado',
    sleepy: 'sonolento',
    sick: 'doente',
    sad: 'triste',
    excited: 'animado',
    happy: 'feliz',
    curious: 'curioso',
    calm: 'calmo'
  };
  return String(source)
    .split(', ')
    .map((part) => states[part.toLowerCase()] || translateCore(part))
    .join(', ');
}

function translateCore(source) {
  if (currentLanguage === 'en') return source;
  if (Object.prototype.hasOwnProperty.call(EXACT_PT, source)) return EXACT_PT[source];

  const colorMatch = source.match(/^([a-z]+) lantern$/i);
  if (colorMatch && COLOR_WORDS[colorMatch[1].toLowerCase()]) {
    return `Lanterna ${COLOR_WORDS[colorMatch[1].toLowerCase()]}`;
  }

  for (const [pattern, formatter] of TEMPLATE_RULES) {
    const match = source.match(pattern);
    if (match) return formatter(match);
  }
  return source;
}

function translateWithWhitespace(source) {
  const match = String(source).match(/^(\s*)([\s\S]*?)(\s*)$/);
  if (!match) return source;
  const [, leading, core, trailing] = match;
  if (!core.trim()) return source;
  return `${leading}${translateCore(core)}${trailing}`;
}

function shouldSkipTextNode(node) {
  const parent = node.parentElement;
  return !parent || ['SCRIPT', 'STYLE', 'NOSCRIPT', 'TEMPLATE'].includes(parent.tagName);
}

function processTextNode(node, refreshSource = false) {
  if (shouldSkipTextNode(node) || !node.nodeValue?.trim()) return;
  let source = textSources.get(node);
  const expected = source ? translateWithWhitespace(source) : null;

  if (!source || refreshSource || (node.nodeValue !== expected && node.nodeValue !== source)) {
    source = node.nodeValue;
    textSources.set(node, source);
  }

  const translated = translateWithWhitespace(source);
  if (node.nodeValue !== translated) node.nodeValue = translated;
}

function processAttribute(element, name, refreshSource = false) {
  if (!element.hasAttribute(name)) return;
  let sources = attributeSources.get(element);
  if (!sources) {
    sources = {};
    attributeSources.set(element, sources);
  }

  const current = element.getAttribute(name);
  const source = sources[name];
  const expected = source ? translateCore(source) : null;
  if (!source || refreshSource || (current !== expected && current !== source)) sources[name] = current;

  const translated = translateCore(sources[name]);
  if (current !== translated) element.setAttribute(name, translated);
}

function processElement(element, refreshSource = false) {
  for (const attribute of TRANSLATABLE_ATTRIBUTES) processAttribute(element, attribute, refreshSource);
  const walker = document.createTreeWalker(element, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) processTextNode(node, refreshSource);
  element.querySelectorAll?.('*').forEach((child) => {
    for (const attribute of TRANSLATABLE_ATTRIBUTES) processAttribute(child, attribute, refreshSource);
  });
}

function syncLanguageControls() {
  document.querySelectorAll('[data-language-select]').forEach((select) => {
    select.value = currentLanguage;
  });
}

export function setLanguage(language, notify = false) {
  currentLanguage = language === 'en' ? 'en' : 'pt-BR';
  document.documentElement.lang = currentLanguage;
  document.documentElement.dir = 'ltr';
  processElement(document.documentElement, false);
  syncLanguageControls();
  if (notify) onLanguageChange?.(currentLanguage);
  window.dispatchEvent(new CustomEvent('languagechange', { detail: { language: currentLanguage } }));
}

export function getLanguage() {
  return currentLanguage;
}

export function translate(source) {
  return translateCore(String(source));
}

export function initI18n({ language = 'pt-BR', onChange } = {}) {
  onLanguageChange = typeof onChange === 'function' ? onChange : null;

  document.querySelectorAll('[data-language-select]').forEach((select) => {
    select.addEventListener('change', (event) => setLanguage(event.target.value, true));
  });

  observer?.disconnect();
  observer = new MutationObserver((mutations) => {
    for (const mutation of mutations) {
      if (mutation.type === 'characterData') {
        processTextNode(mutation.target, false);
      } else if (mutation.type === 'attributes') {
        processAttribute(mutation.target, mutation.attributeName, false);
      } else {
        mutation.addedNodes.forEach((node) => {
          if (node.nodeType === Node.TEXT_NODE) processTextNode(node, false);
          if (node.nodeType === Node.ELEMENT_NODE) processElement(node, false);
        });
      }
    }
  });

  observer.observe(document.documentElement, {
    subtree: true,
    childList: true,
    characterData: true,
    attributes: true,
    attributeFilter: TRANSLATABLE_ATTRIBUTES
  });

  setLanguage(language, false);
}
